    public static function create(): int
    {
        $id = Repo::saveCompetition([
            'name'       => self::NAME,
            'event_date' => date('Y-m-d'),
            'location'   => '中央公園 周回コース（1周 2km）',
            'team_size'  => 3,
            'status'     => 'preparing',
            'note'       => '動作確認・操作練習用のサンプル大会です。不要になったら「大会設定」から削除してください。',
        ]);
        $teams = [];
        foreach (self::TEAMS as [$bib, $name, $category, $open, $note, $runners]) {
            $teams[] = [
                'bib'        => $bib,
                'name'       => $name,
                'category'   => $category,
                'force_open' => $open,
                'note'       => $note,
                'runners'    => array_map(fn ($r) => [
                    'name' => $r[0], 'kana' => $r[1], 'gender' => $r[2], 'age' => $r[3], 'affiliation' => $r[4], 'note' => '',
                ], $runners),
            ];
        }
        Roster::import($id, $teams, 'replace');
        return $id;
    }

    /** 大会が 1 件も無ければサンプルを登録する */
    public static function createIfEmpty(): void
    {
        if ((int) Db::value('SELECT COUNT(*) FROM competitions') === 0) {
            self::create();
        }
    }
